import { DynamicWorkerExecutor } from '@cloudflare/codemode'
import { codeMcpServer } from '@cloudflare/codemode/mcp'
import { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js'
import { WebStandardStreamableHTTPServerTransport } from '@modelcontextprotocol/sdk/server/webStandardStreamableHttp.js'
import { z } from 'zod'

const id = z.string().regex(/^[0-9a-f]{32}$/)
const key = z.string().min(8).max(128)
const title = z.string().min(1).max(160)
const target = z.enum(['android', 'asterisk']).optional()
const requestFields = { title, body: z.string().max(16000), expiresAt: z.string(), idempotencyKey: key }
const securityLevel = z.enum(['standard', 'elevated']).optional()
const shape = z.object({
  id: z.string().max(64),
  label: z.string().max(160),
  type: z.enum(['text', 'boolean', 'single_choice', 'multi_choice', 'number']),
  required: z.boolean().optional(),
  options: z.array(z.object({ id: z.string(), label: z.string() })).optional(),
  min: z.number().optional(),
  max: z.number().optional(),
  maxLength: z.number().optional(),
})

function addTools(server, actor, request, readOnly) {
  function tool(name, description, inputSchema, scopes, invoke) {
    if (!scopes.some(scope => actor.scopes.includes(scope))) return
    server.registerTool(name, { description, inputSchema }, async args => {
      try {
        const result = await invoke(args)
        return { content: [{ type: 'text', text: JSON.stringify(result) }] }
      } catch (error) {
        return { isError: true, content: [{ type: 'text', text: error.message }] }
      }
    })
  }

  function notification(kind, { idempotencyKey, ...input }) {
    return request('POST', '/notifications', { kind, ...input }, { 'Idempotency-Key': idempotencyKey })
  }

  tool('get_request', 'Read a request owned by this integration.', { id }, ['requests:read'],
    args => request('GET', '/notifications/' + args.id))
  tool('wait_for_response', 'Wait up to 25 seconds for a response to an owned request.', {
    id, seconds: z.number().int().min(0).max(25).optional(),
  }, ['requests:read'], args => request('GET', '/notifications/' + args.id + '/wait?seconds=' + (args.seconds ?? 20)))
  tool('get_call_status', 'Read the state of a call started by this source.', { id },
    ['calls:start', 'calls:announce', 'agents:connect'], args => request('GET', '/calls/' + args.id))
  tool('get_call_transcript', 'Read the protected transcript of an owned conversation.', { id },
    ['calls:start', 'agents:connect'], args => request('GET', '/calls/' + args.id + '/transcript'))

  if (readOnly) return

  tool('send_notification', 'Send an informational notification.', {
    title, body: z.string().max(16000), idempotencyKey: key, iconId: z.string().optional(),
  }, ['notify:send'], args => notification('message', args))
  tool('send_voice', 'Send a voice notification generated by Notify Silero.', {
    title, text: z.string().min(1).max(1000), expiresAt: z.string(), idempotencyKey: key,
  }, ['notify:send'], ({ text, ...args }) => notification('voice', { ...args, body: text, voiceText: text }))
  tool('request_confirmation', 'Request a decision. Only an answered yes approves the described action.', {
    ...requestFields, securityLevel, allowCustom: z.boolean().optional(),
  }, ['requests:create'], args => notification('confirmation', args))
  tool('request_form', 'Request a structured decision form.', {
    ...requestFields, securityLevel, fields: z.array(shape).min(1).max(20),
  }, ['requests:create'], ({ fields, ...args }) => notification('form', { ...args, form: { fields } }))
  tool('cancel_request', 'Cancel an owned pending request.', { id }, ['requests:cancel'],
    args => request('POST', '/notifications/' + args.id + '/cancel'))
  tool('upload_icon', 'Upload a PNG or WebP icon as base64.', {
    mimeType: z.enum(['image/png', 'image/webp']), base64: z.string().min(4).max(350000),
  }, ['icons:write'], ({ mimeType, base64 }) => {
    let bytes
    try { bytes = Uint8Array.from(atob(base64), c => c.charCodeAt(0)) }
    catch { throw new Error('invalid_base64') }
    return request('POST', '/icons', bytes, { 'Content-Type': mimeType })
  })
  tool('start_call', 'Ring the selected phone and speak text after manual answer.', {
    title, text: z.string().min(1).max(300), idempotencyKey: key, target,
  }, ['calls:start', 'calls:announce', 'agents:connect'], args => request('POST', '/calls/announce', args))
  tool('start_conversation', 'Ring the selected phone for a conversation. Use sessionId for a bound chat.', {
    title, idempotencyKey: key, target, sessionId: z.string().min(1).max(64).optional(),
  }, ['calls:start', 'agents:connect'], args => request('POST', '/calls/conversation', args))
  tool('speak_call', 'Speak a reply in an active conversation started without a bound chat.', {
    id, text: z.string().min(1).max(1000), idempotencyKey: key,
  }, ['calls:start'], ({ id: callId, ...args }) => request('POST', '/calls/' + callId + '/say', args))
}

export default {
  async fetch(incoming, env) {
    const route = new URL(incoming.url).pathname
    if (route !== '/mcp' && route !== '/mcp/read') return new Response(null, { status: 404 })
    const authorization = incoming.headers.get('Authorization')
    if (!authorization?.startsWith('Bearer ')) return new Response(null, { status: 401 })
    const origin = new URL(env.NOTIFY_ORIGIN)
    if (origin.protocol !== 'https:' && !(origin.protocol === 'http:' && env.NOTIFY_LOCAL === '1')) {
      return Response.json({ code: "invalid_notify_origin" }, { status: 503 })
    }
    let remaining = 20
    async function request(method, path, data, headers = {}) {
      if (--remaining < 0) throw new Error('operation_limit')
      let response
      try {
        response = await fetch(origin.origin + '/api/v1' + path, {
          method, headers: { Authorization: authorization, 'Content-Type': 'application/json', ...headers },
          body: data instanceof Uint8Array || data === undefined ? data : JSON.stringify(data),
          redirect: 'manual', signal: AbortSignal.timeout(30000),
        })
      } catch (error) {
        console.warn('Notify upstream transport:', error.name)
        throw new Error('notify_unreachable')
      }
      if (response.status >= 300 && response.status < 400) throw new Error('notify_redirect_refused')
      if (response.status === 204) return { ok: true }
      const result = await response.json().catch(() => null)
      if (!response.ok || result === null) {
        const code = result?.code
        throw new Error(typeof code === 'string' && /^[a-z0-9_]{1,64}$/.test(code) ? code : 'notify_' + response.status)
      }
      return result
    }

    let actor
    try { ({ actor } = await request('GET', '/session')) }
    catch (error) {
      return Response.json({ code: error.message }, { status: error.message === 'notify_401' ? 401 : 503 })
    }
    if (actor?.kind !== 'integration' || !Array.isArray(actor.scopes)) return new Response(null, { status: 403 })

    const upstream = new McpServer({ name: 'notify', version: '1.0.0' })
    addTools(upstream, actor, request, route === '/mcp/read')
    const executor = new DynamicWorkerExecutor({ loader: env.LOADER })
    const server = await codeMcpServer({ server: upstream, executor })
    const transport = new WebStandardStreamableHTTPServerTransport({ enableJsonResponse: true })
    await server.connect(transport)
    try { return await transport.handleRequest(incoming) }
    finally { await server.close() }
  },
}
